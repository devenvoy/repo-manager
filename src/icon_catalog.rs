/// Render a known language icon at 18 pixels.
pub fn language_icon(language: Language) -> Icon {
    icon(language.svg())
}
/// Match a name and render its icon. Unknown names receive a generic SVG.
pub fn language_icon_for_name(name: &str) -> Icon {
    icon(Language::from_name(name).map_or(GENERIC_SVG, Language::svg))
}
/// Render a known file format icon at 18 pixels.
pub fn file_type_icon(kind: FileType) -> Icon {
    icon(kind.svg())
}
/// Match an extension and render its icon. Unknown extensions receive a generic SVG.
pub fn file_type_icon_for_extension(extension: &str) -> Icon {
    icon(FileType::from_extension(extension).map_or(GENERIC_SVG, FileType::svg))
}
/// Match a file path and render its icon, including compound extensions.
pub fn file_type_icon_for_path(path: &Path) -> Icon {
    icon(FileType::from_path(path).map_or(GENERIC_SVG, FileType::svg))
}
const GENERIC_SVG: &[u8] = include_bytes!("../resources/catalog-icons/document.svg");
fn icon(data: &'static [u8]) -> Icon {
    Icon::default().data(data).w(px(18.)).h(px(18.))
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn language_aliases_and_colors() {
        assert_eq!(Language::from_name("  TS  "), Some(Language::TypeScript));
        assert_eq!(Language::from_name("c++"), Some(Language::Cpp));
        assert_eq!(Language::from_name("unknown"), None);
        assert_eq!(Language::Rust.color().rgb(), 0xDEA584);
    }
    #[test]
    fn extensions_and_paths() {
        assert_eq!(FileType::from_extension(".JPG"), Some(FileType::Image));
        assert_eq!(
            FileType::from_path(Path::new("release.TAR.GZ")),
            Some(FileType::Tar)
        );
        assert_eq!(
            FileType::from_path(Path::new("release.test.tar.gz")),
            Some(FileType::Tar)
        );
        assert_eq!(
            FileType::from_path(Path::new("foo.test.ts")),
            Some(FileType::TypeScript)
        );
        assert_eq!(FileType::from_extension("not-real"), None);
    }
    #[test]
    fn all_entries_have_svg_assets() {
        for language in Language::ALL {
            assert!(language.svg().starts_with(b"<svg") || language.svg().starts_with(b"<?xml"));
        }
        for kind in FileType::ALL {
            assert!(kind.svg().starts_with(b"<svg") || kind.svg().starts_with(b"<?xml"));
        }
    }
}
